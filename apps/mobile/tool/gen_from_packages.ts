/**
 * Generates Dart from the shared TypeScript packages so the Flutter app and the admin never drift:
 *   lib/design/tokens.g.dart   ← packages/design-tokens (colours light/dark, spacing, radii, type scale, motion)
 *   lib/brand/geometry.g.dart  ← packages/brand (Atelier A paths, phases, stroke per size)
 *   lib/l10n/messages.g.dart   ← packages/shared/src/i18n (en + sw)
 * Run:  pnpm --filter @smartwear/brand exec tsx ../../apps/mobile/tool/gen_from_packages.ts
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { palette, space, radii, fontSizes, lineHeights, letterSpacing, textStyles, durations, easings, springs, pressScale } from '../../../packages/design-tokens/src/index';
import { A_GEOMETRY, LOADER_PHASES, LOADER_LOOP_MS, LOADER_EASING, LOADER_SIZES, LOADER_STROKE, LOADER_STITCH_STROKE, LOADER_NEEDLE_RADIUS, BREATHE_SCALE, REDUCED_MOTION_PULSE } from '../../../packages/brand/src/loader';
import { en } from '../../../packages/shared/src/i18n/en';
import { sw } from '../../../packages/shared/src/i18n/sw';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const header = '// GENERATED by tool/gen_from_packages.ts — do not edit by hand.\n// ignore_for_file: constant_identifier_names, lines_longer_than_80_chars\n';
const out = (rel: string, body: string) => {
  const p = join(root, rel);
  mkdirSync(dirname(p), { recursive: true });
  writeFileSync(p, header + body);
  console.log('wrote', rel);
};
const hex = (c: string) => {
  const m = c.match(/^#([0-9a-f]{6})$/i);
  if (m) return `Color(0xFF${m[1]!.toUpperCase()})`;
  const r = c.match(/rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)/);
  if (r) return `Color.fromRGBO(${r[1]}, ${r[2]}, ${r[3]}, ${r[4]})`;
  throw new Error(`colour ${c}`);
};
const id = (k: string) => k.replace(/[^a-zA-Z0-9]/g, '_').replace(/^(\d)/, 'n$1');
const dstr = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$').replace(/\n/g, '\\n')}'`;

// ---------------------------------------------------------------- tokens
{
  const keys = Object.keys(palette) as (keyof typeof palette)[];
  let b = "import 'package:flutter/painting.dart';\n\n";
  b += '/// Colour scheme for one theme — the only colours screens may use.\n@immutable\nclass SwColors {\n';
  b += `  const SwColors({${keys.map((k) => `required this.${k}`).join(', ')}});\n`;
  for (const k of keys) b += `  final Color ${k};\n`;
  b += '\n  static const light = SwColors(\n' + keys.map((k) => `    ${k}: ${hex(palette[k].light)},`).join('\n') + '\n  );\n';
  b += '  static const dark = SwColors(\n' + keys.map((k) => `    ${k}: ${hex(palette[k].dark)},`).join('\n') + '\n  );\n';
  b += `\n  static SwColors lerp(SwColors a, SwColors b, double t) => SwColors(${keys.map((k) => `${k}: Color.lerp(a.${k}, b.${k}, t)!`).join(', ')});\n}\n\n`;
  b += '/// 8-pt grid.\nabstract final class SwSpace {\n' + Object.entries(space).map(([k, v]) => `  static const double s${String(k).replace('.', '_')} = ${v};`).join('\n') + '\n}\n\n';
  b += 'abstract final class SwRadius {\n' + Object.entries(radii).map(([k, v]) => `  static const double ${k} = ${v === 9999 ? 999 : v};`).join('\n') + '\n}\n\n';
  b += 'abstract final class SwFontSize {\n' + Object.entries(fontSizes).map(([k, v]) => `  static const double ${id(k.replace('2xl', 'x2l').replace('3xl', 'x3l').replace('4xl', 'x4l'))} = ${v};`).join('\n') + '\n}\n\n';
  b += 'abstract final class SwTracking {\n' + Object.entries(letterSpacing).map(([k, v]) => `  /// em\n  static const double ${k} = ${v};`).join('\n') + '\n}\n\n';
  b += '/// Named text styles (family, size, weight, tracking em, line height px, uppercase).\nclass SwTextSpec {\n  const SwTextSpec(this.display, this.size, this.weight, this.trackingEm, this.lineHeight, {this.uppercase = false});\n  final bool display;\n  final double size;\n  final int weight;\n  final double trackingEm;\n  final double lineHeight;\n  final bool uppercase;\n}\n\n';
  b += 'abstract final class SwTextSpecs {\n';
  for (const [k, s] of Object.entries(textStyles)) {
    const spec = s as { family: string; size: keyof typeof fontSizes; weight: number; tracking: keyof typeof letterSpacing; lineHeight: number; uppercase?: boolean };
    b += `  static const ${k} = SwTextSpec(${spec.family === 'display'}, ${fontSizes[spec.size]}, ${spec.weight}, ${letterSpacing[spec.tracking]}, ${spec.lineHeight}${spec.uppercase ? ', uppercase: true' : ''});\n`;
  }
  b += '}\n\n';
  b += 'abstract final class SwMotion {\n' + Object.entries(durations).map(([k, v]) => `  static const Duration ${k} = Duration(milliseconds: ${v});`).join('\n');
  b += '\n' + Object.entries(easings).map(([k, v]) => `  static const Cubic ${k} = Cubic(${v.join(', ')});`).join('\n');
  b += '\n' + Object.entries(springs).map(([k, v]) => `  /// damping, stiffness, mass\n  static const List<double> spring_${k} = [${v.damping}, ${v.stiffness}, ${v.mass}];`).join('\n');
  b += `\n  static const double pressScale = ${pressScale};\n}\n`;
  b = b.replace("import 'package:flutter/painting.dart';", "import 'package:flutter/animation.dart';\nimport 'package:flutter/foundation.dart';\nimport 'package:flutter/painting.dart';");
  out('lib/design/tokens.g.dart', b);
}

// ---------------------------------------------------------------- brand geometry
{
  const g = A_GEOMETRY;
  let b = '/// The Atelier A — same geometry and timing as the web loader (viewBox 100×100).\nabstract final class AGeometry {\n';
  b += `  static const double apexX = ${g.apex.x}, apexY = ${g.apex.y};\n  static const double baseLeftX = ${g.baseLeft.x}, baseLeftY = ${g.baseLeft.y};\n  static const double baseRightX = ${g.baseRight.x}, baseRightY = ${g.baseRight.y};\n`;
  b += `  static const double crossY = ${g.crossbar.y}, crossX1 = ${g.crossbar.x1}, crossX2 = ${g.crossbar.x2};\n`;
  b += `  static const double legLength = ${g.legLength};\n  static const double crossbarLength = ${g.crossbarLength};\n  static const List<double> stitchDash = [${g.stitchDash.join(', ')}];\n`;
  b += `  static const String sparklePath = '${g.sparklePath}';\n}\n\n`;
  b += 'class APhase {\n  const APhase(this.start, this.end);\n  final double start, end;\n  double progress(double t) => t <= start ? 0 : t >= end ? 1 : (t - start) / (end - start);\n}\n\n';
  b += 'abstract final class ALoaderTiming {\n';
  b += `  static const Duration loop = Duration(milliseconds: ${LOADER_LOOP_MS});\n  static const List<double> easing = [${LOADER_EASING.join(', ')}];\n  static const double breatheScale = ${BREATHE_SCALE};\n`;
  for (const [k, p] of Object.entries(LOADER_PHASES)) b += `  static const ${k} = APhase(${p.start}, ${p.end});\n`;
  b += `  static const double pulseMin = ${REDUCED_MOTION_PULSE.min}, pulseMax = ${REDUCED_MOTION_PULSE.max};\n  static const Duration pulsePeriod = Duration(milliseconds: ${REDUCED_MOTION_PULSE.periodMs});\n}\n\n`;
  b += 'enum ALoaderSize {\n' + (Object.keys(LOADER_SIZES) as (keyof typeof LOADER_SIZES)[]).map((k) => `  ${k}(${LOADER_SIZES[k]}, ${LOADER_STROKE[k]}, ${LOADER_STITCH_STROKE[k]}, ${LOADER_NEEDLE_RADIUS[k]})`).join(',\n') + ';\n\n';
  b += '  const ALoaderSize(this.px, this.stroke, this.stitchStroke, this.needleRadius);\n  final double px;\n  /// stroke widths in viewBox units\n  final double stroke, stitchStroke, needleRadius;\n}\n';
  out('lib/brand/geometry.g.dart', b);
}

// ---------------------------------------------------------------- i18n
{
  const keys = Object.keys(en) as (keyof typeof en)[];
  let b = '/// English and Swahili catalogs from packages/shared/src/i18n. Missing Swahili keys fall back to English.\n';
  b += 'const Map<String, String> messagesEn = {\n' + keys.map((k) => `  ${dstr(k)}: ${dstr(en[k])},`).join('\n') + '\n};\n\n';
  b += 'const Map<String, String> messagesSw = {\n' + Object.entries(sw).map(([k, v]) => `  ${dstr(k)}: ${dstr(v as string)},`).join('\n') + '\n};\n';
  out('lib/l10n/messages.g.dart', b);
}
